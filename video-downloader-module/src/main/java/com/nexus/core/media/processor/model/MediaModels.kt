/**
 * 处理事件
 */
sealed class ProcessingEvent {
    data class TaskCreated(val task: ProcessingTask) : ProcessingEvent()
    data class TaskStarted(val task: ProcessingTask) : ProcessingEvent()
    data class TaskProgress(val task: ProcessingTask, val progress: Int) : ProcessingEvent()
    data class TaskPaused(val task: ProcessingTask) : ProcessingEvent()
    data class TaskResumed(val task: ProcessingTask) : ProcessingEvent()
    data class TaskCompleted(val task: ProcessingTask) : ProcessingEvent()
    data class TaskFailed(val task: ProcessingTask, val error: String) : ProcessingEvent()
    data class TaskCancelled(val task: ProcessingTask) : ProcessingEvent()
    data class TaskDeleted(val taskId: String) : ProcessingEvent()
}