/**
 * 缩略图信息
 */
@Parcelize
data class ThumbnailInfo(
    /** 缩略图ID */
    val id: String,
    
    /** 缩略图URL */
    val url: String,
    
    /** 宽度 */
    val width: Int,
    
    /** 高度 */
    val height: Int,
    
    /** 分辨率描述 */
    val resolution: String? = null,
    
    /** 文件扩展名 */
    val extension: String? = null,
    
    /** 文件大小 */
    val fileSize: Long? = null,
    
    /** 偏好值 */
    val preference: Int? = null
) : Parcelable {
    
    /**
     * 获取分辨率字符串
     */
    fun getResolutionString(): String {
        return resolution ?: "${width}x${height}"
    }
    
    /**
     * 获取像素总数
     */
    fun getPixelCount(): Int {
        return width * height
    }
    
    /**
     * 检查是否为高清缩略图
     */
    fun isHighDefinition(): Boolean {
        return width >= 1280 || height >= 720
    }
}

/**
 * 字幕信息
 */
@Parcelize
data class SubtitleInfo(
    /** 字幕ID */
    val id: String,
    
    /** 语言代码 */
    val language: String,
    
    /** 语言名称 */
    val languageName: String,
    
    /** 字幕URL */
    val url: String,
    
    /** 字幕格式 */
    val format: String,
    
    /** 文件扩展名 */
    val extension: String,
    
    /** 是否为自动生成 */
    val isAutoGenerated: Boolean = false,
    
    /** 是否为默认字幕 */
    val isDefault: Boolean = false,
    
    /** 文件大小 */
    val fileSize: Long? = null
) : Parcelable {
    
    /**
     * 获取显示名称
     */
    fun getDisplayName(): String {
        val autoTag = if (isAutoGenerated) " (自动)" else ""
        val defaultTag = if (isDefault) " (默认)" else ""
        return "$languageName$autoTag$defaultTag"
    }
}

/**
 * 章节信息
 */
@Parcelize
data class ChapterInfo(
    /** 章节标题 */
    val title: String,
    
    /** 开始时间(秒) */
    val startTime: Float,
    
    /** 结束时间(秒) */
    val endTime: Float?
) : Parcelable {
    
    /**
     * 获取章节时长
     */
    fun getDuration(): Float? {
        return endTime?.let { it - startTime }
    }
    
    /**
     * 获取格式化的开始时间
     */
    fun getFormattedStartTime(): String {
        return formatTime(startTime)
    }
    
    /**
     * 获取格式化的结束时间
     */
    fun getFormattedEndTime(): String? {
        return endTime?.let { formatTime(it) }
    }
    
    /**
     * 获取格式化的时长
     */
    fun getFormattedDuration(): String? {
        return getDuration()?.let { formatTime(it) }
    }
    
    private fun formatTime(seconds: Float): String {
        val totalSeconds = seconds.toInt()
        val hours = totalSeconds / 3600
        val minutes = (totalSeconds % 3600) / 60
        val secs = totalSeconds % 60
        
        return if (hours > 0) {
            String.format("%d:%02d:%02d", hours, minutes, secs)
        } else {
            String.format("%d:%02d", minutes, secs)
        }
    }
}

/**
 * 媒体质量枚举
 */
enum class MediaQuality {
    BEST,       // 最佳质量
    WORST,      // 最低质量
    UHD_4K,     // 4K超高清
    QHD_2K,     // 2K高清
    FHD_1080P,  // 1080P全高清
    HD_720P,    // 720P高清
    SD_480P,    // 480P标清
    SD_360P,    // 360P标清
    SD_240P,    // 240P标清
    LOW,        // 低质量 (≤480p)
    MEDIUM,     // 中等质量 (481p-720p)
    HIGH,       // 高质量 (721p-1080p)
    ULTRA,      // 超高质量 (>1080p)
    AUDIO_ONLY  // 仅音频
}

